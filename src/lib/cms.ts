export function sortActive<T extends CmsItem>(items: T[]) {
  return [...items]
    .filter((item) => item.active !== false)
    .sort((a, b) => Number(a.order ?? 0) - Number(b.order ?? 0));
}

export function getCmsCollection<T extends CmsItem = CmsItem>(collection: CmsCollection): T[] {
  if (!canUseStorage()) return cmsSeed[collection] as T[];

  try {
    const raw = window.localStorage.getItem(cmsKey(collection));
    return raw ? JSON.parse(raw) : (cmsSeed[collection] as T[]);
  } catch {
    return cmsSeed[collection] as T[];
  }
}

export function saveCmsCollection<T extends CmsItem>(collection: CmsCollection, items: T[]) {
  if (!canUseStorage()) return;
  window.localStorage.setItem(cmsKey(collection), JSON.stringify(items));
  window.dispatchEvent(new CustomEvent(cmsEventName, { detail: { collection } }));
}

export function useCmsCollection<T extends CmsItem = CmsItem>(collection: CmsCollection) {
  const [items, setItems] = useState<T[]>(() => getCmsCollection<T>(collection));

  useEffect(() => {
    const sync = () => setItems(getCmsCollection<T>(collection));
    sync();
    window.addEventListener("storage", sync);
    window.addEventListener(cmsEventName, sync);
    return () => {
      window.removeEventListener("storage", sync);
      window.removeEventListener(cmsEventName, sync);
    };
  }, [collection]);

  const activeItems = useMemo(() => sortActive(items), [items]);

  return { items, activeItems, setItems: (next: T[]) => saveCmsCollection(collection, next) };
}

export function upsertCmsItem<T extends CmsItem>(items: T[], item: T) {
  const exists = items.some((current) => current.id === item.id);
  return exists ? items.map((current) => (current.id === item.id ? item : current)) : [...items, item];
}
